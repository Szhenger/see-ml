std::expected<EmitPaths, std::string> EmitNativePackage(
    const std::vector<uint8_t>& plan, const std::string& out_dir,
    const std::string& repo_root) {
  std::error_code ec;
  std::filesystem::create_directories(out_dir, ec);
  if (ec)
    return generating::FileError(generating::kNativeEmitter,
                                 "cannot create", out_dir);

  EmitPaths paths{
      .plan_file = out_dir + "/update_plan.seeu",
      .embedded_tu = out_dir + "/update_plan_embedded.cc",
      .main_tu = out_dir + "/update_main.cc",
      .build_script = out_dir + "/build.sh",
  };

  {
    std::ofstream f(paths.plan_file, std::ios::binary | std::ios::trunc);
    if (!f)
      return generating::Error(generating::kNativeEmitter,
                               "cannot write plan file");
    f.write(reinterpret_cast<const char*>(plan.data()),
            static_cast<std::streamsize>(plan.size()));
    f.close();
    if (f.fail())
      return generating::FileError(generating::kNativeEmitter,
                                   "short write to", paths.plan_file);
  }
  if (auto r = WriteFile(paths.embedded_tu, EmbedPlanAsTU(plan)); !r)
    return std::unexpected(r.error());
  if (auto r = WriteFile(paths.main_tu, kMainTU); !r)
    return std::unexpected(r.error());

  // Vendor the runtime into the package so it builds without the repo.
  for (const char* rel : kVendoredSources) {
    const auto src = std::filesystem::path(repo_root) / rel;
    const auto dst = std::filesystem::path(out_dir) / rel;
    std::filesystem::create_directories(dst.parent_path(), ec);
    if (ec)
      return generating::FileError(generating::kNativeEmitter,
                                   "cannot create",
                                   dst.parent_path().string());
    std::filesystem::copy_file(
        src, dst, std::filesystem::copy_options::overwrite_existing, ec);
    if (ec)
      return generating::Error(generating::kNativeEmitter,
                               "cannot vendor '" + src.string() + "' (" +
                                   ec.message() + ")");
  }

  // Wire the architecture analysis into the delivered program: the tiling
  // suggested for this host becomes the package's default GEMM geometry.
  // Two-tier discipline: the suggestion is gated through its own contract,
  // and a violation falls back to the kernel's portable defaults instead of
  // failing the emission — a bad hint may cost throughput, never the build.
  const HostArchInfo arch = DetectHostArch();
  GemmTiling tiling = SuggestGemmTiling(arch);
  const GemmTiling* tiling_for_script = &tiling;
  if (auto ok = ValidateGemmTiling(tiling, arch); !ok) {
    seeml::diag::Fallback(generating::kNativeEmitter,
                          "suggested GEMM tiling failed its contract (" +
                              ok.error() +
                              ") — falling back to portable default tiles");
    tiling_for_script = nullptr;
  }

  if (auto r = WriteFile(paths.build_script, BuildScript(tiling_for_script),
                         /*executable=*/true);
      !r)
    return std::unexpected(r.error());

  return paths;
}

