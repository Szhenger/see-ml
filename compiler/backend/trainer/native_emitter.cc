std::string BuildScript(const GemmTiling* tiling) {
  std::string s;
  s += "#!/bin/sh\n";
  s += "# Generated by seeml-update-compile: builds the self-contained\n";
  s += "# `model_update` executable from the vendored runtime sources.\n";
  s += "# Cross-compile by setting CXX to your target toolchain.\n";
  s += "set -e\n";
  s += "cd \"$(dirname \"$0\")\"\n";
  s += "CXX=\"${CXX:-c++}\"\n";
  if (tiling) {
    s += "# GEMM tile geometry derived by the compiler's architecture\n";
    s += "# analysis from THIS compile host's cache hierarchy (kc x nc\n";
    s += "# panel of B within half of L1). It is a throughput knob only —\n";
    s += "# results are bit-identical for any tiling the kernel accepts.\n";
    s += "# Cross-compiling for a device with different caches? Override\n";
    s += "# it, or clear it to the kernel's portable defaults:\n";
    s += "#   SEEML_TILE_FLAGS=\"\" sh build.sh\n";
    s += "TILE_FLAGS=\"${SEEML_TILE_FLAGS--DSEEML_GEMM_TILE_K=" +
         std::to_string(tiling->kc) +
         " -DSEEML_GEMM_TILE_N=" + std::to_string(tiling->nc) + "}\"\n";
  } else {
    s += "TILE_FLAGS=\"${SEEML_TILE_FLAGS-}\"\n";
  }
  s += "# -pthread: the runtime parallelizes its kernels and pipelines the\n";
  s += "# batch feeder; SEEML_THREADS=1 at run time restores fully serial\n";
  s += "# execution (with bit-identical results — chunking is fixed).\n";
  s += "FLAGS=\"-std=c++23 -O2 -Wall -Wextra -pthread -I. $TILE_FLAGS\"\n";
  s += "$CXX $FLAGS -c update_plan_embedded.cc -o update_plan_embedded.o\n";
  s += "$CXX $FLAGS -c update_main.cc -o update_main.o\n";
  s += "$CXX $FLAGS -c source/parallel/parallel_for.cc -o parallel_for.o\n";
  s += "for unit in executor/gemm executor/elementwise executor/activation "
       "executor/normalization executor/loss executor/optimizer "
       "executor/attention "
       "feeder/dataset feeder/batch_pipeline validator/plan_validator "
       "custodian/durable_io custodian/checkpoint engine/contract "
       "engine/update_engine; do\n";
  s += "  $CXX $FLAGS -c \"runtime/$unit.cc\" -o \"$(basename $unit).o\"\n";
  s += "done\n";
  s += "$CXX $FLAGS update_main.o update_plan_embedded.o update_engine.o "
       "contract.o dataset.o batch_pipeline.o gemm.o elementwise.o "
       "activation.o normalization.o loss.o optimizer.o attention.o "
       "parallel_for.o durable_io.o plan_validator.o checkpoint.o "
       "-o model_update\n";
  s += "# The .o files are intermediates; the deliverable is the binary.\n";
  s += "rm -f ./*.o\n";
  s += "echo \"built: $(pwd)/model_update\"\n";
  return s;
}

